"""
Agent 3b: SQL Validation and Execution Tool.

This component independently validates and executes SQL generated by
Agent 3a.

Validation layers:

1. SQLValidator structural safety validation.
2. Referenced table and view validation.
3. Role, column, and privacy-policy validation.
4. SQLite EXPLAIN QUERY PLAN validation.
5. Read-only database execution.
6. Configured maximum result-row enforcement.

This component does not:

- Generate SQL.
- Call an LLM.
- Modify the database.
- Apply Northwind-specific business rules.
- Silently correct invalid SQL.

Any error produced by this component can later be sent back to
Agent 3a through the LangGraph retry loop.
"""

import sqlite3
import time
import re
from dataclasses import dataclass
from typing import Any, Optional

from database.db_manager import (
    DatabaseManager,
    QueryResult,
)
from models.schemas import QueryExecutionResult
from security.models import (
    SchemaPolicyResult,
    UserRole,
)
from security.schema_policy import (
    SchemaPolicyValidator,
)
from tools.sql_validator import (
    SQLValidationResult,
    SQLValidator,
)


@dataclass
class SQLExecutionOutcome:
    """
    Complete outcome of Agent 3b.

    A successful outcome contains query_result.

    A failed outcome contains validation_errors or execution_error.
    """

    success: bool
    validated_sql: Optional[str]
    validation_result: Optional[SQLValidationResult]
    query_result: Optional[QueryExecutionResult]
    validation_errors: list[str]
    execution_error: Optional[str]
    retryable: bool
    stage: str
    schema_policy_result: Optional[
        SchemaPolicyResult
    ] = None



class SQLExecutionTool:
    """
    Safely validates and executes read-only SQLite queries.

    DatabaseManager provides read-only database access while
    SQLValidator provides syntax-tree-based SQL safety validation.
    """

    def __init__(
    self,
    database_manager: DatabaseManager,
    sql_validator: SQLValidator,
    schema_policy_validator: Optional[
        SchemaPolicyValidator
    ] = None,
    role: UserRole | str = UserRole.ANALYST,
    explain_before_execution: bool = True,
) -> None:
        """
        Initialize Agent 3b.

        Args:
            database_manager:
                Existing read-only DatabaseManager.

            sql_validator:
                Existing SQLValidator configured for SQLite.

            explain_before_execution:
                Whether SQLite EXPLAIN QUERY PLAN must succeed before
                executing the query.
        """

        if not isinstance(
            database_manager,
            DatabaseManager,
        ):
            raise TypeError(
                "database_manager must be a "
                "DatabaseManager instance."
            )

        if not isinstance(
            sql_validator,
            SQLValidator,
        ):
            raise TypeError(
                "sql_validator must be a "
                "SQLValidator instance."
            )
        if (
            schema_policy_validator is not None
            and not isinstance(
                schema_policy_validator,
                SchemaPolicyValidator,
            )
        ):
            raise TypeError(
                "schema_policy_validator must be a "
                "SchemaPolicyValidator instance."
            )

        try:
            normalized_role = UserRole(role)

        except ValueError as exc:
            raise ValueError(
                "role must be one of: viewer, analyst, admin."
            ) from exc

        if not isinstance(
            explain_before_execution,
            bool,
        ):
            raise TypeError(
                "explain_before_execution must be a boolean."
            )

        self.database_manager = database_manager
        self.sql_validator = sql_validator

        self.schema_policy_validator = (
            schema_policy_validator
            if schema_policy_validator is not None
            else SchemaPolicyValidator(
                database_manager=database_manager,
                sql_validator=sql_validator,
                maximum_result_rows=(
                    database_manager.max_rows
                ),
            )
        )

        self.role = normalized_role

        self.explain_before_execution = (
            explain_before_execution
        )

    def _normalize_object_name(
        self,
        object_name: str,
    ) -> str:
        """
        Normalize a table or view name for comparison.

        SQLite identifiers are case-insensitive in normal usage.
        """

        return " ".join(
            object_name.strip().lower().split()
        )

    def _get_allowed_schema_objects(
        self,
    ) -> dict[str, str]:
        """
        Return all approved tables and views.

        The dictionary maps normalized names to their original names.
        Values are discovered dynamically from SQLite metadata.
        """

        table_names = (
            self.database_manager.get_tables()
        )

        view_names = (
            self.database_manager.get_views()
        )

        allowed_objects: dict[str, str] = {}

        for object_name in [
            *table_names,
            *view_names,
        ]:
            normalized_name = (
                self._normalize_object_name(
                    object_name
                )
            )

            allowed_objects[
                normalized_name
            ] = object_name

        return allowed_objects

    def _validate_referenced_tables(
        self,
        validation_result: SQLValidationResult,
    ) -> list[str]:
        """
        Validate that every referenced table or view exists.

        Returns:
            A list of validation errors.
        """

        errors: list[str] = []

        allowed_objects = (
            self._get_allowed_schema_objects()
        )

        for referenced_table in (
            validation_result.referenced_tables
        ):
            normalized_name = (
                self._normalize_object_name(
                    referenced_table
                )
            )

            if normalized_name not in allowed_objects:
                errors.append(
                    "SQL references a table or view that does "
                    "not exist in the approved database schema: "
                    f"{referenced_table}"
                )

        if not validation_result.referenced_tables:
            errors.append(
                "The SQL query does not reference an approved "
                "database table or view."
            )

        return errors

    def _run_explain_query_plan(
        self,
        sql: str,
    ) -> list[dict[str, Any]]:
        """
        Ask SQLite to compile the query without executing it.

        EXPLAIN QUERY PLAN detects issues such as:

        - Missing tables
        - Missing columns
        - Invalid joins
        - Ambiguous columns
        - Invalid functions or expressions
        - SQLite syntax incompatibility

        Returns:
            SQLite query-plan records.

        Raises:
            RuntimeError:
                If SQLite cannot compile the query.
        """

        explain_sql = (
            f"EXPLAIN QUERY PLAN {sql}"
        )

        try:
            with (
                self.database_manager.get_connection()
                as connection
            ):
                cursor = connection.execute(
                    explain_sql
                )

                rows = cursor.fetchall()

                return [
                    dict(row)
                    for row in rows
                ]

        except sqlite3.Error as exc:
            error_text = str(exc)
            missing_column_hint = (
                self._build_missing_column_hint(
                    error_text
                )
            )
            if missing_column_hint:
                error_text = (
                    f"{error_text}\n"
                    f"{missing_column_hint}"
                )

            raise RuntimeError(
                "SQLite could not compile the generated SQL.\n"
                f"Database error: {error_text}"
            ) from exc

    def _build_missing_column_hint(
        self,
        error_text: str,
    ) -> Optional[str]:
        """
        Find the actual table that owns a missing column.

        SQLite reports missing names but not alternate locations.
        Searching the live database metadata lets Agent 3a receive
        precise, schema-derived retry guidance.
        """
        match = re.search(
            r"no such column:\s*([^\r\n]+)",
            error_text,
            flags=re.IGNORECASE,
        )
        if not match:
            return None

        reference = match.group(1).strip()
        column_name = reference.rsplit(".", 1)[-1]
        normalized_column = column_name.lower()

        owners: list[str] = []
        for table_name in (
            self.database_manager.get_tables()
        ):
            for column in (
                self.database_manager.get_columns(
                    table_name
                )
            ):
                if (
                    str(column["name"]).lower()
                    == normalized_column
                ):
                    owners.append(table_name)
                    break

        if not owners:
            return None

        owner_text = ", ".join(
            f'"{owner}"'
            for owner in owners
        )
        return (
            f"Schema guidance: '{column_name}' exists "
            f"in the following table(s): {owner_text}. "
            "Do not reference it on a table that does not "
            "declare the column."
        )

    def _convert_query_result(
        self,
        result: QueryResult,
    ) -> QueryExecutionResult:
        """
        Convert DatabaseManager QueryResult into the shared
        Pydantic QueryExecutionResult.
        """

        return QueryExecutionResult(
            columns=result.columns,
            rows=result.rows,
            row_count=result.row_count,
            execution_time_ms=(
                result.execution_time_ms
            ),
            truncated=result.truncated,
            query=result.query,
        )

    def _validation_failure(
    self,
    validation_result: Optional[
        SQLValidationResult
    ],
    errors: list[str],
    stage: str,
    validated_sql: Optional[str] = None,
    schema_policy_result: Optional[
        SchemaPolicyResult
    ] = None,
    retryable: bool = True,
) -> SQLExecutionOutcome:
        """
    Create a failed validation outcome.
        """

        return SQLExecutionOutcome(
        success=False,
        validated_sql=validated_sql,
        validation_result=validation_result,
        query_result=None,
        validation_errors=errors,
        execution_error=None,
        retryable=retryable,
        stage=stage,
        schema_policy_result=(
            schema_policy_result
        ),
    )


    def _execution_failure(
    self,
    validation_result: SQLValidationResult,
    validated_sql: str,
    error: Exception,
    stage: str,
    schema_policy_result: Optional[
        SchemaPolicyResult
    ] = None,
) -> SQLExecutionOutcome:
        """
    Create a failed execution outcome.

    Database error text is retained for Agent 3a correction.
    """

        return SQLExecutionOutcome(
        success=False,
        validated_sql=validated_sql,
        validation_result=validation_result,
        query_result=None,
        validation_errors=[],
        execution_error=str(error),
        retryable=True,
        stage=stage,
        schema_policy_result=(
            schema_policy_result
        ),
    )

    def validate_and_execute(
        self,
        sql: str,
    ) -> SQLExecutionOutcome:
        """
        Validate and execute one read-only SQL query.

        Processing order:

        1. Structural SQL validation
        2. Table and view existence validation
        3. Role, column, and privacy-policy validation
        4. SQLite EXPLAIN QUERY PLAN
        5. Read-only execution
        6. Pydantic result validation
        """

        if not isinstance(sql, str):
            return self._validation_failure(
                validation_result=None,
                errors=[
                    "SQL must be provided as a string."
                ],
                stage="input_validation",
            )

        cleaned_sql = sql.strip()

        if not cleaned_sql:
            return self._validation_failure(
                validation_result=None,
                errors=[
                    "SQL cannot be empty."
                ],
                stage="input_validation",
            )

        validation_result = (
            self.sql_validator.validate(
                cleaned_sql
            )
        )

        if not validation_result.is_valid:
            return self._validation_failure(
                validation_result=validation_result,
                errors=validation_result.errors,
                stage="structural_validation",
            )

        normalized_sql = (
            validation_result.normalized_sql
        )

        if not normalized_sql:
            return self._validation_failure(
                validation_result=validation_result,
                errors=[
                    "SQL validation succeeded but no "
                    "normalized SQL was returned."
                ],
                stage="structural_validation",
            )

        schema_errors = (
            self._validate_referenced_tables(
                validation_result
            )
        )

        if schema_errors:
            return self._validation_failure(
                validation_result=validation_result,
                errors=schema_errors,
                stage="schema_validation",
            )

        schema_policy_result = (
            self.schema_policy_validator.validate(
                sql=normalized_sql,
                role=self.role,
            )
        )

        if not schema_policy_result.allowed:
            policy_errors = [
                (
                    f"{finding.violation_type}: "
                    f"{finding.message}"
                )
                for finding
                in schema_policy_result.findings
            ]

            if not policy_errors:
                policy_errors = [
                    (
                        "The generated SQL was rejected "
                        "by schema and privacy policy."
                    )
                ]

            # The SQL may be regenerated when Agent 3a selected a
            # protected column. SQLite execution is never reached.
            return self._validation_failure(
                validation_result=validation_result,
                errors=policy_errors,
                stage="schema_policy_validation",
                validated_sql=normalized_sql,
                schema_policy_result=(
                    schema_policy_result
                ),
                retryable=True,
            )

        if self.explain_before_execution:
            try:
                self._run_explain_query_plan(
                    normalized_sql
                )

            except RuntimeError as exc:
                return self._execution_failure(
                    validation_result=(
                        validation_result
                    ),
                    validated_sql=normalized_sql,
                    error=exc,
                    stage="explain_validation",
                    schema_policy_result=(
                        schema_policy_result
                    ),
                )

        try:
            database_result = (
                self.database_manager
                .execute_read_query(
                    normalized_sql
                )
            )

        except Exception as exc:
            return self._execution_failure(
                validation_result=(
                    validation_result
                ),
                validated_sql=normalized_sql,
                error=exc,
                stage="result_validation",
                schema_policy_result=(
                    schema_policy_result
                ),
            )

        try:
            query_result = (
                self._convert_query_result(
                    database_result
                )
            )

        except Exception as exc:
            return self._execution_failure(
                validation_result=(
                    validation_result
                ),
                validated_sql=normalized_sql,
                error=exc,
                stage="result_validation",
            )

        return SQLExecutionOutcome(
                success=True,
                validated_sql=normalized_sql,
                validation_result=validation_result,
                query_result=query_result,
                validation_errors=[],
                execution_error=None,
                retryable=False,
                stage="completed",
                schema_policy_result=(
                    schema_policy_result
                ),
            )


def main() -> None:
    """
    Run Agent 3b against the real Northwind database.

    The smoke test uses dynamically discovered database metadata rather
    than a hardcoded business query.
    """

    print("=" * 80)
    print(
        "AGENT 3B: SQL VALIDATION AND EXECUTION "
        "SMOKE TEST"
    )
    print("=" * 80)

    try:
        database_manager = DatabaseManager(
            max_rows=100,
        )

        sql_validator = SQLValidator(
            dialect="sqlite"
        )

        schema_policy_validator = (
    SchemaPolicyValidator(
        database_manager=database_manager,
        sql_validator=sql_validator,
        maximum_result_rows=100,
            )
        )

        execution_tool = SQLExecutionTool(
            database_manager=database_manager,
            sql_validator=sql_validator,
            schema_policy_validator=(
                schema_policy_validator
            ),
            role=UserRole.ANALYST,
            explain_before_execution=True,
        )

        available_tables = (
            database_manager.get_tables()
        )

        if not available_tables:
            raise RuntimeError(
                "The database contains no tables."
            )

        selected_table = (
            available_tables[0]
        )

        escaped_table = (
            selected_table.replace(
                '"',
                '""',
            )
        )

        test_sql = f"""
            SELECT *
            FROM "{escaped_table}"
            LIMIT 5;
        """

        print(
            f"Selected table : {selected_table}"
        )

        print("\nSQL:")
        print(test_sql.strip())

        outcome = (
            execution_tool
            .validate_and_execute(
                test_sql
            )
        )

        print(
            f"\nSuccess       : "
            f"{outcome.success}"
        )

        print(
            f"Stage         : "
            f"{outcome.stage}"
        )

        if outcome.validation_errors:
            print(
                f"Validation errors: "
                f"{outcome.validation_errors}"
            )

        if outcome.execution_error:
            print(
                f"Execution error: "
                f"{outcome.execution_error}"
            )

        if outcome.schema_policy_result is not None:
            print(
                f"Policy allowed: "
                f"{outcome.schema_policy_result.allowed}"
            )

            print(
                f"Policy role   : "
                f"{outcome.schema_policy_result.role}"
            )

            print(
                f"Redacted cols : "
                f"{outcome.schema_policy_result.redacted_output_columns}"
            )

            if outcome.schema_policy_result.findings:
                print("Policy findings:")

                for finding in (
                    outcome
                    .schema_policy_result
                    .findings
                ):
                    print(
                        f"- {finding.violation_type}: "
                        f"{finding.message}"
                    )


        if not outcome.success:
            raise RuntimeError(
                "Agent 3b smoke test failed."
            )

        if outcome.query_result is None:
            raise RuntimeError(
                "Agent 3b returned no query result."
            )

        print(
            f"Columns       : "
            f"{outcome.query_result.columns}"
        )

        print(
            f"Rows returned : "
            f"{outcome.query_result.row_count}"
        )

        print(
            f"Truncated     : "
            f"{outcome.query_result.truncated}"
        )

        print(
            f"Execution time: "
            f"{outcome.query_result.execution_time_ms} ms"
        )

        print("\nRows:")

        for row in outcome.query_result.rows:
            print(row)

        print("\n" + "=" * 80)
        print("RESULT: AGENT 3B IS WORKING")
        print("=" * 80)

    except Exception as exc:
        print("\n" + "=" * 80)
        print("RESULT: AGENT 3B FAILED")
        print("=" * 80)
        print(
            f"{type(exc).__name__}: {exc}"
        )
        raise SystemExit(1) from exc


if __name__ == "__main__":
    main()