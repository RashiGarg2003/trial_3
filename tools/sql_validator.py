"""
SQL safety validator for the Multi-Agent Data Analytics System.

This component validates SQL generated by the SQL Agent before the
query reaches the database.

Responsibilities:

1. Reject empty SQL.
2. Remove Markdown code fences.
3. Parse SQL using the SQLite dialect.
4. Allow only one SQL statement.
5. Allow only read-only query statements.
6. Reject database modification and administrative operations.
7. Return referenced tables and columns.
8. Return normalized SQLite SQL.

This component does not:

- Generate SQL.
- Execute SQL.
- Use an LLM.
- Contain Northwind-specific table or column names.
"""

from dataclasses import dataclass

from sqlglot import exp, parse
from sqlglot.errors import ParseError


@dataclass
class SQLValidationResult:
    """
    Structured result returned by SQLValidator.
    """

    is_valid: bool
    original_sql: str
    normalized_sql: str | None
    statement_type: str | None
    referenced_tables: list[str]
    referenced_columns: list[str]
    errors: list[str]


class SQLValidationError(ValueError):
    """
    Raised when SQL fails safety validation.
    """


class SQLValidator:
    """
    Validates read-only analytical SQL.

    The validator uses SQLGlot's parsed syntax tree rather than
    depending only on text or keyword matching.
    """

    def __init__(
        self,
        dialect: str = "sqlite",
    ) -> None:
        """
        Initialize the SQL validator.

        Args:
            dialect:
                SQL dialect used for parsing and normalization.
        """

        if not isinstance(dialect, str):
            raise TypeError(
                "dialect must be a string."
            )

        cleaned_dialect = dialect.strip().lower()

        if not cleaned_dialect:
            raise ValueError(
                "dialect cannot be empty."
            )

        self.dialect = cleaned_dialect

    def clean_sql(
        self,
        sql: str,
    ) -> str:
        """
        Remove common LLM formatting around SQL.

        SQLCoder may return SQL inside Markdown code fences. This method
        removes only those presentation markers and preserves the query.
        """

        if not isinstance(sql, str):
            raise TypeError(
                "sql must be a string."
            )

        cleaned_sql = sql.strip()

        if not cleaned_sql:
            raise SQLValidationError(
                "SQL cannot be empty."
            )

        if cleaned_sql.startswith("```"):
            lines = cleaned_sql.splitlines()

            if lines:
                opening_line = lines[0].strip().lower()

                if opening_line in {
                    "```",
                    "```sql",
                    "```sqlite",
                }:
                    lines = lines[1:]

            if lines and lines[-1].strip() == "```":
                lines = lines[:-1]

            cleaned_sql = "\n".join(lines).strip()

        if not cleaned_sql:
            raise SQLValidationError(
                "SQL is empty after removing formatting."
            )

        return cleaned_sql

    def _get_forbidden_expression_types(
        self,
    ) -> tuple[type[exp.Expression], ...]:
        """
        Return SQLGlot expression classes representing unsafe operations.

        getattr() is used because expression availability can vary
        between SQLGlot versions.
        """

        forbidden_names = (
            "Insert",
            "Update",
            "Delete",
            "Create",
            "Drop",
            "Alter",
            "TruncateTable",
            "Merge",
            "Replace",
            "Command",
            "Transaction",
            "Commit",
            "Rollback",
            "Grant",
            "Revoke",
            "Attach",
            "Detach",
            "Use",
            "Set",
            "Copy",
            "LoadData",
            "Into",
        )

        forbidden_types: list[
            type[exp.Expression]
        ] = []

        for expression_name in forbidden_names:
            expression_type = getattr(
                exp,
                expression_name,
                None,
            )

            if (
                isinstance(expression_type, type)
                and issubclass(
                    expression_type,
                    exp.Expression,
                )
            ):
                forbidden_types.append(
                    expression_type
                )

        return tuple(forbidden_types)

    def _is_read_only_query(
        self,
        statement: exp.Expression,
    ) -> bool:
        """
        Determine whether the root statement is a query expression.

        This supports SELECT queries, common table expressions, unions,
        intersections, and other SQLGlot query expressions.
        """

        query_type = getattr(
            exp,
            "Query",
            None,
        )

        if (
            isinstance(query_type, type)
            and isinstance(statement, query_type)
        ):
            return True

        allowed_root_names = {
            "Select",
            "Union",
            "Intersect",
            "Except",
            "Subquery",
        }

        return (
            statement.__class__.__name__
            in allowed_root_names
        )

    def _find_forbidden_operations(
        self,
        statement: exp.Expression,
    ) -> list[str]:
        """
        Find unsafe operations anywhere in the syntax tree.
        """

        forbidden_types = (
            self._get_forbidden_expression_types()
        )

        if not forbidden_types:
            return []

        discovered_operations: set[str] = set()

        for node in statement.walk():
            if isinstance(node, forbidden_types):
                discovered_operations.add(
                    node.__class__.__name__
                )

        return sorted(discovered_operations)

    def _extract_referenced_tables(
        self,
        statement: exp.Expression,
    ) -> list[str]:
        """
        Return physical table names referenced by the query.

        Common table expression aliases are removed because they are
        temporary query names rather than database tables.
        """

        cte_aliases = {
            cte.alias_or_name
            for cte in statement.find_all(exp.CTE)
            if cte.alias_or_name
        }

        table_names: list[str] = []
        normalized_names: set[str] = set()

        for table in statement.find_all(exp.Table):
            table_name = table.name

            if not table_name:
                continue

            if table_name in cte_aliases:
                continue

            database_name = table.db
            catalog_name = table.catalog

            name_parts = [
                part
                for part in (
                    catalog_name,
                    database_name,
                    table_name,
                )
                if part
            ]

            complete_name = ".".join(name_parts)
            normalized_name = complete_name.lower()

            if normalized_name in normalized_names:
                continue

            normalized_names.add(normalized_name)
            table_names.append(complete_name)

        return table_names

    def _extract_referenced_columns(
        self,
        statement: exp.Expression,
    ) -> list[str]:
        """
        Return columns referenced by the query.

        Qualified columns are returned as table.column when available.
        """

        column_names: list[str] = []
        normalized_names: set[str] = set()

        for column in statement.find_all(exp.Column):
            column_name = column.name

            if not column_name:
                continue

            table_name = column.table

            if table_name:
                complete_name = (
                    f"{table_name}.{column_name}"
                )
            else:
                complete_name = column_name

            normalized_name = complete_name.lower()

            if normalized_name in normalized_names:
                continue

            normalized_names.add(normalized_name)
            column_names.append(complete_name)

        return column_names

    def validate(
        self,
        sql: str,
    ) -> SQLValidationResult:
        """
        Validate SQL and return a structured result.

        This method does not raise for normal validation failures.
        It returns is_valid=False with explanatory errors.
        """

        original_sql = (
            sql
            if isinstance(sql, str)
            else str(sql)
        )

        errors: list[str] = []

        try:
            cleaned_sql = self.clean_sql(sql)

        except (
            TypeError,
            SQLValidationError,
        ) as exc:
            return SQLValidationResult(
                is_valid=False,
                original_sql=original_sql,
                normalized_sql=None,
                statement_type=None,
                referenced_tables=[],
                 referenced_columns=[],
          errors=[str(exc)],
            )

        try:
            statements = parse(
                cleaned_sql,
                read=self.dialect,
            )

        except ParseError as exc:
            return SQLValidationResult(
                is_valid=False,
                original_sql=original_sql,
                normalized_sql=None,
                statement_type=None,
                referenced_tables=[],
                referenced_columns=[],
                errors=[
                    f"SQL parsing failed: {exc}"
                ],
            )

        non_empty_statements = [
            statement
            for statement in statements
            if statement is not None
        ]

        if len(non_empty_statements) != 1:
            return SQLValidationResult(
                is_valid=False,
                original_sql=original_sql,
                normalized_sql=None,
                statement_type=None,
                referenced_tables=[],
                referenced_columns=[],
                errors=[
                    "Exactly one SQL statement is allowed. "
                    f"Received {len(non_empty_statements)}."
                ],
            )

        statement = non_empty_statements[0]
        statement_type = (
            statement.__class__.__name__
        )

        if not self._is_read_only_query(statement):
            errors.append(
                "Only read-only query statements are allowed. "
                f"Received statement type: {statement_type}."
            )

        forbidden_operations = (
            self._find_forbidden_operations(
                statement
            )
        )

        if forbidden_operations:
            errors.append(
                "Unsafe SQL operations were detected: "
                + ", ".join(forbidden_operations)
            )

        referenced_tables = (
            self._extract_referenced_tables(
                statement
            )
        )

        referenced_columns = (
            self._extract_referenced_columns(
                statement
            )
        )

        try:
            normalized_sql = statement.sql(
                dialect=self.dialect,
                pretty=True,
            )

        except Exception as exc:
            errors.append(
                "SQL normalization failed: "
                f"{exc}"
            )

            normalized_sql = None

        return SQLValidationResult(
            is_valid=not errors,
            original_sql=original_sql,
            normalized_sql=normalized_sql,
            statement_type=statement_type,
            referenced_tables=referenced_tables,
            referenced_columns=referenced_columns,
            errors=errors,
        )

    def validate_or_raise(
        self,
        sql: str,
    ) -> SQLValidationResult:
        """
        Validate SQL and raise when the query is unsafe or invalid.

        Returns:
            Successful SQLValidationResult.

        Raises:
            SQLValidationError:
                If validation fails.
        """

        result = self.validate(sql)

        if not result.is_valid:
            formatted_errors = "\n".join(
                f"- {error}"
                for error in result.errors
            )

            raise SQLValidationError(
                "SQL validation failed:\n"
                f"{formatted_errors}"
            )

        return result


def main() -> None:
    """
    Run a standalone SQL Validator smoke test.
    """

    print("=" * 80)
    print("SQL VALIDATOR SMOKE TEST")
    print("=" * 80)

    validator = SQLValidator(
        dialect="sqlite"
    )

    safe_sql = """
        SELECT
            category,
            SUM(amount) AS total_amount
        FROM sales
        GROUP BY category
        ORDER BY total_amount DESC
        LIMIT 5;
    """

    unsafe_sql = """
        DROP TABLE sales;
    """

    print("\nTesting read-only SQL:")

    safe_result = validator.validate(
        safe_sql
    )

    print(
        f"Valid              : "
        f"{safe_result.is_valid}"
    )
    print(
        f"Statement type     : "
        f"{safe_result.statement_type}"
    )
    print(
        f"Referenced tables  : "
        f"{safe_result.referenced_tables}"
    )
    print(
        f"Referenced columns : "
        f"{safe_result.referenced_columns}"
    )
    print(
        f"Errors             : "
        f"{safe_result.errors}"
    )

    print("\nNormalized SQL:")
    print(safe_result.normalized_sql)

    print("\nTesting unsafe SQL:")

    unsafe_result = validator.validate(
        unsafe_sql
    )

    print(
        f"Valid          : "
        f"{unsafe_result.is_valid}"
    )
    print(
        f"Statement type : "
        f"{unsafe_result.statement_type}"
    )
    print(
        f"Errors         : "
        f"{unsafe_result.errors}"
    )

    if not safe_result.is_valid:
        raise RuntimeError(
            "The safe SELECT query was incorrectly rejected."
        )

    if unsafe_result.is_valid:
        raise RuntimeError(
            "The unsafe DROP query was incorrectly accepted."
        )

    print("\n" + "=" * 80)
    print("RESULT: SQL VALIDATOR IS WORKING")
    print("=" * 80)


if __name__ == "__main__":
    main()
